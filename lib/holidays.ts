const HOLIDAY_CAPTION_KEY_PREFIX = 'holidays.captions.';

interface HolidayMarker {
  captionKey: string;
  emoji: string;
}

/**
 * Возвращает данные праздника для даты (ключ MM-DD) или null.
 */
export function getHolidayForDate(date: Date): HolidayMarker | null {
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  const key = `${month}-${day}`;
  const emoji = HOLIDAY_EMOJIS[key];
  if (!emoji) {
    return null;
  }
  return { captionKey: `${HOLIDAY_CAPTION_KEY_PREFIX}${key}`, emoji };
}
